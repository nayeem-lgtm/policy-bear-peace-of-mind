describe('Identity split', () => {
  it('waits on Back and advances again after an identity selection', () => {
    open('identity')
    fireEvent.change(screen.getByRole('combobox', { name: 'Country of birth' }), { target: { value: 'Canada' } })
    fireEvent.click(screen.getByRole('radio', { name: /^Yes$/ }))
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-ssn')
    act(() => { window.location.hash = '#step-identity'; window.dispatchEvent(new HashChangeEvent('hashchange')) })
    act(() => { vi.advanceTimersByTime(800) })
    expect(window.location.hash).toBe('#step-identity')
    fireEvent.change(screen.getByRole('combobox', { name: 'Country of birth' }), { target: { value: 'Other' } })
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-ssn')
  })
  it('automatically routes noncitizens after their residency choice', () => {
    open('identity')
    fireEvent.change(screen.getByRole('combobox', { name: 'Country of birth' }), { target: { value: 'Canada' } })
    fireEvent.click(screen.getByRole('radio', { name: /^No$/ }))
    const residencyNo = screen.getAllByRole('radio', { name: /^No$/ })[1]
    if (!residencyNo) throw new Error('Residency choice is missing')
    fireEvent.click(residencyNo)
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-ineligible')
  })
  it('auto-advances identity to the separate SSN step', () => {
    open('identity')
    fireEvent.change(screen.getByRole('combobox', { name: 'Country of birth' }), { target: { value: 'Canada' } })
    fireEvent.click(screen.getByRole('radio', { name: /^Yes$/ }))
    act(() => { vi.advanceTimersByTime(800) })
    expect(window.location.hash).toBe('#step-ssn')
  })
  it('requires nine SSN digits before opening the separate policy-owner step', () => {
    open('ssn')
    const input = screen.getByLabelText('Social Security number')
    fireEvent.change(input, { target: { value: '12345678' } })
    expect(screen.getByRole('button', { name: 'Next' })).toBeDisabled()
    fireEvent.change(input, { target: { value: '123456789' } })
    fireEvent.click(screen.getByRole('button', { name: 'Next' }))
    expect(window.location.hash).toBe('#step-owner')
    fireEvent.click(screen.getByRole('button', { name: /Go back/ }))
    expect(window.location.hash).toBe('#step-ssn')
    expect(screen.getByLabelText('Social Security number')).toHaveValue('123-45-6789')
    const saved = JSON.parse(localStorage.getItem('policybear-demo') || '{}')
    expect(saved.answers).not.toHaveProperty('ssn')
  })
  it.each([['Yes', 'h1'], ['No', 'ineligible']])('advances the policy-owner choice %s to %s', (choice, next) => {
    open('owner')
    fireEvent.click(screen.getByRole('radio', { name: new RegExp(`^${choice}$`) }))
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe(`#step-${next}`)
  })
})

describe('Application auto-advance', () => {
  it('edits coverage from congratulations and returns with the updated amount', () => {
    open('decision', { coverage: '15000', firstName: 'Ann' })
    fireEvent.click(screen.getByRole('button', { name: 'Make changes' }))
    expect(window.location.hash).toBe('#step-price')
    fireEvent.change(screen.getByRole('slider'), { target: { value: '20000' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save changes' }))
    expect(window.location.hash).toBe('#step-decision')
    const saved = JSON.parse(localStorage.getItem('policybear-demo') || '{}')
    expect(saved.answers.coverage).toBe('20000')
    fireEvent.click(screen.getByRole('button', { name: 'Finalize' }))
    expect(window.location.hash).toBe('#step-payment')
  })
  it('automatically moves through all eight health answers directly to beneficiary', () => {
    open('h1')
    for (let index = 1; index <= 8; index += 1) {
      expect(window.location.hash).toBe(`#step-h${index}`)
      fireEvent.click(screen.getByRole('radio', { name: /^No$/ }))
      act(() => { vi.advanceTimersByTime(350) })
    }
    expect(window.location.hash).toBe('#step-beneficiary')
  })
  it('allows selecting the same health answer again after Back', () => {
    open('h1')
    fireEvent.click(screen.getByRole('radio', { name: /^Yes$/ }))
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-h2')
    fireEvent.click(screen.getByRole('button', { name: /Go back/ }))
    expect(window.location.hash).toBe('#step-h1')
    fireEvent.click(screen.getByRole('radio', { name: /^Yes$/ }))
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-h2')
  })
  it('moves on from other insurance when No is chosen', () => {
    open('insurance')
    fireEvent.click(screen.getByRole('radio', { name: /^No/ }))
    act(() => { vi.advanceTimersByTime(400) })
    expect(window.location.hash).toBe('#step-underwriting')
    act(() => { vi.advanceTimersByTime(3200) })
    expect(window.location.hash).toBe('#step-decision')
    fireEvent.click(screen.getByRole('button', { name: 'Finalize' }))
    expect(window.location.hash).toBe('#step-payment')
    fireEvent.click(screen.getByRole('button', { name: /Go back/ }))
    expect(window.location.hash).toBe('#step-decision')
    fireEvent.click(screen.getByRole('button', { name: /Go back/ }))
    expect(window.location.hash).toBe('#step-insurance')
    fireEvent.click(screen.getByRole('radio', { name: /^No$/ }))
    act(() => { vi.advanceTimersByTime(400) })
    expect(window.location.hash).toBe('#step-underwriting')
    act(() => { vi.advanceTimersByTime(3200) })
    expect(window.location.hash).toBe('#step-decision')
  })
  it.each(['No', 'Yes'])('shows congratulations after the replacement answer %s', (answer) => {
    open('insurance')
    fireEvent.click(screen.getByRole('radio', { name: /^Yes$/ }))
    act(() => { vi.advanceTimersByTime(400) })
    expect(window.location.hash).toBe('#step-insurance')
    fireEvent.click(within(screen.getByRole('radiogroup', { name: 'Replacement policy' })).getByRole('radio', { name: answer }))
    act(() => { vi.advanceTimersByTime(400) })
    expect(window.location.hash).toBe('#step-underwriting')
    act(() => { vi.advanceTimersByTime(3200) })
    expect(window.location.hash).toBe('#step-decision')
    fireEvent.click(screen.getByRole('button', { name: /Go back/ }))
    expect(window.location.hash).toBe('#step-insurance')
    fireEvent.click(within(screen.getByRole('radiogroup', { name: 'Replacement policy' })).getByRole('radio', { name: answer }))
    act(() => { vi.advanceTimersByTime(400) })
    act(() => { vi.advanceTimersByTime(3200) })
    expect(window.location.hash).toBe('#step-decision')
  })
  it('goes directly from the final health answer to beneficiary and back to health', () => {
    open('h8')
    fireEvent.click(screen.getByRole('radio', { name: /^No$/ }))
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-beneficiary')
    fireEvent.click(screen.getByRole('button', { name: /Go back/ }))
    expect(window.location.hash).toBe('#step-h8')
  })
  it('preserves the declined offer before beneficiary and celebrates accepted guaranteed coverage after insurance', () => {
    open('h8', { health: ['Yes'] })
    fireEvent.click(screen.getByRole('radio', { name: /^No$/ }))
    act(() => { vi.advanceTimersByTime(350) })
    expect(window.location.hash).toBe('#step-eligibility')
    fireEvent.click(screen.getByRole('button', { name: 'See guaranteed coverage' }))
    expect(window.location.hash).toBe('#step-gi-offer')
    fireEvent.click(screen.getByRole('button', { name: 'Next' }))
    expect(window.location.hash).toBe('#step-beneficiary')
    fireEvent.change(screen.getByRole('combobox', { name: 'Beneficiary type' }), { target: { value: 'My estate' } })
    fireEvent.click(screen.getByRole('button', { name: 'Next' }))
    fireEvent.click(screen.getByRole('radio', { name: /^No$/ }))
    act(() => { vi.advanceTimersByTime(400) })
    expect(window.location.hash).toBe('#step-underwriting')
    act(() => { vi.advanceTimersByTime(3200) })
    expect(window.location.hash).toBe('#step-decision')
    fireEvent.click(screen.getByRole('button', { name: 'Finalize' }))
    expect(window.location.hash).toBe('#step-payment')
  })
  it('keeps the person details on the beneficiary page', () => {
    open('beneficiary')
    fireEvent.change(screen.getByRole('combobox', { name: 'Beneficiary type' }), { target: { value: 'A person' } })
    expect(window.location.hash).toBe('#step-beneficiary')
    expect(screen.getByRole('textbox', { name: 'First name' })).toBeInTheDocument()
  })
  it('reveals the phone number box when the customer knows it', () => {
    open('beneficiary')
    const phoneGroup = screen.getByRole('radiogroup', { name: 'Do you know the phone number for this beneficiary?' })
    expect(screen.queryByRole('textbox', { name: 'Phone number' })).not.toBeInTheDocument()
    fireEvent.click(within(phoneGroup).getByRole('radio', { name: 'Yes' }))
    expect(screen.getByRole('textbox', { name: 'Phone number' })).toBeInTheDocument()
  })
  it('holds the beneficiary step until the name, relationship and contact answers are given', () => {
    open('beneficiary')
    fireEvent.change(screen.getByRole('combobox', { name: 'Beneficiary type' }), { target: { value: 'A person' } })
    fireEvent.click(screen.getByRole('button', { name: /^Next/ }))
    expect(screen.getByRole('alert')).toBeInTheDocument()
    expect(window.location.hash).toBe('#step-beneficiary')
    fireEvent.change(screen.getByRole('textbox', { name: 'First name' }), { target: { value: 'Jane' } })
    fireEvent.change(screen.getByRole('textbox', { name: 'Last name' }), { target: { value: 'Doe' } })
    fireEvent.change(screen.getByRole('combobox', { name: 'Relationship' }), { target: { value: 'Daughter' } })
    fireEvent.click(screen.getByRole('button', { name: /^Next/ }))
    expect(window.location.hash).toBe('#step-beneficiary')
    fireEvent.click(within(screen.getByRole('radiogroup', { name: 'Do you know the phone number for this beneficiary?' })).getByRole('radio', { name: 'No' }))
    fireEvent.click(within(screen.getByRole('radiogroup', { name: 'Do you know the address for this beneficiary?' })).getByRole('radio', { name: 'No' }))
    fireEvent.click(screen.getByRole('button', { name: /^Next/ }))
    expect(window.location.hash).toBe('#step-insurance')
  })
})
